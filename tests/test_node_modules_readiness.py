"""A half-installed node_modules must not look ready.

Reported from a second Mac: preparation died inside Metro with

    the package `.../node_modules/axios/package.json` was successful ...
    this package itself specifies a `main` module field that could not be
    resolved (`.../node_modules/axios/dist/browser/axios.cjs`).
    Indeed, none of these files exist

axios was not the problem. node_modules was present but incomplete -- each
package.json in place, the files their `main` points at missing -- and every
`os.path.isdir("node_modules")` check passed, so the platform bundled anyway
and let Metro fail with an error that named the wrong culprit.

node_modules is gitignored, so this is the NORMAL state of a fresh clone on
another machine, which makes it a portability bug rather than a one-off.
"""
import json
import os

import pytest

from automation.projects.builder import app_builder


def _write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f)


# The REAL axios manifest, trimmed to the fields that matter. Reproduced
# verbatim because the first version of this test invented a package whose
# `main` was the missing file — which is NOT what axios looks like, and the
# implementation passed that test while failing on the real thing.
AXIOS_MANIFEST = {
    "name": "axios", "version": "1.7.7",
    "main": "index.js",
    "exports": {
        ".": {
            "types": {"require": "./index.d.cts", "default": "./index.d.ts"},
            "browser": {"require": "./dist/browser/axios.cjs", "default": "./index.js"},
            "default": {"require": "./dist/node/axios.cjs", "default": "./index.js"},
        },
        "./lib/*": "./lib/*",
    },
}


def _pkg(repo, name, *, main="index.js", with_file=True, manifest=None):
    """Register *name* as a dependency and lay down its node_modules entry."""
    pj = os.path.join(repo, "package.json")
    data = json.load(open(pj)) if os.path.isfile(pj) else {"dependencies": {}}
    data.setdefault("dependencies", {})[name] = "^1.0.0"
    _write(pj, data)

    d = os.path.join(repo, "node_modules", *name.split("/"))
    _write(os.path.join(d, "package.json"),
           manifest or {"name": name, "version": "1.0.0", "main": main})
    if with_file:
        entry = (manifest or {}).get("main", main)
        target = os.path.join(d, entry)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        open(target, "w").write("module.exports = {};\n")


@pytest.fixture
def repo(tmp_path):
    r = tmp_path / "app"
    r.mkdir()
    _write(str(r / "package.json"), {"name": "app", "dependencies": {}})
    return str(r)


