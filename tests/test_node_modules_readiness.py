def test_14_wildcard_subpath_patterns_are_not_files(repo):
    """`"./lib/*": "./lib/*"` is a template Node expands, not a path on disk.

    Flagged axios, ramda and geolib — all three install correctly and bundle.
    """
    _pkg(repo, "axios", manifest=AXIOS_MANIFEST)
    d = os.path.join(repo, "node_modules", "axios")
    os.makedirs(os.path.join(d, "dist", "browser"), exist_ok=True)
    open(os.path.join(d, "dist", "browser", "axios.cjs"), "w").write("x")
    os.makedirs(os.path.join(d, "dist", "node"), exist_ok=True)
    open(os.path.join(d, "dist", "node", "axios.cjs"), "w").write("x")
    for f in ("index.d.cts", "index.d.ts"):
        open(os.path.join(d, f), "w").write("x")
    assert app_builder._unusable_node_modules(repo) == [], \
        "a wildcard export pattern was treated as a missing file"


def test_15_secondary_export_subpaths_do_not_gate_a_build(repo):
    """Only exports["."] decides whether requiring the package works.

    react-day-picker declares "./examples" and ships no examples/ directory;
    lucide-react declares "./dist/cjs/dynamic.js" and omits it. Both bundle fine
    because nothing imports those subpaths.
    """
    _pkg(repo, "day-picker", manifest={
        "name": "day-picker", "version": "1", "main": "dist/index.js",
        "exports": {".": "./dist/index.js",
                    "./examples": "./examples/index.ts"},   # absent on disk
    }, with_file=False)
    d = os.path.join(repo, "node_modules", "day-picker", "dist")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "index.js"), "w").write("x")
    assert app_builder._unusable_node_modules(repo) == [], \
        "a missing optional subpath blocked the build"


