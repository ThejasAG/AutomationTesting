def test_02_the_reported_failure_is_detected(repo):
    """The real thing: axios's `main` RESOLVES, its exports path does not.

    This is the test the first implementation should have had. It shipped with a
    fabricated axios whose `main` was the missing file, which passed while the
    real failure went straight through: on actual axios `main` is index.js and
    the unresolvable path (dist/browser/axios.cjs) lives only under `exports`.
    """
    _pkg(repo, "axios", manifest=AXIOS_MANIFEST)      # index.js written
    _pkg(repo, "react-native")
    assert os.path.isfile(os.path.join(repo, "node_modules", "axios", "index.js")), \
        "the fixture must reproduce a PRESENT main, or it tests nothing"
    assert app_builder._unusable_node_modules(repo) == ["axios"]


