"""A half-installed node_modules must not look ready.

Reported from a second Mac: preparation died inside Metro with

    the package `.../node_modules/axios/package.json` was successful ...
    this package itself specifies a `main` module field that could not be
    resolved (`.../node_modules/axios/dist/browser/axios.cjs`).
    Indeed, none of these files exist

axios was not the problem. node_modules was present but incomplete -- each
package.json in place, the files their `main` points at missing -- and every
`os.path.isdir("node_modules")` check passed, so the platform bundled anyway
and let Metro fail with an error that named the wrong culprit.

node_modules is gitignored, so this is the NORMAL state of a fresh clone on
another machine, which makes it a portability bug rather than a one-off.
"""
import json
import os

import pytest

from automation.projects.builder import app_builder


def _write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f)


def _pkg(repo, name, *, main="index.js", with_file=True):
    """Register *name* as a dependency and lay down its node_modules entry."""
    pj = os.path.join(repo, "package.json")
    data = json.load(open(pj)) if os.path.isfile(pj) else {"dependencies": {}}
    data.setdefault("dependencies", {})[name] = "^1.0.0"
    _write(pj, data)

    d = os.path.join(repo, "node_modules", *name.split("/"))
    _write(os.path.join(d, "package.json"), {"name": name, "version": "1.0.0",
                                             "main": main})
    if with_file:
        target = os.path.join(d, main)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        open(target, "w").write("module.exports = {};\n")


@pytest.fixture
def repo(tmp_path):
    r = tmp_path / "app"
    r.mkdir()
    _write(str(r / "package.json"), {"name": "app", "dependencies": {}})
    return str(r)


# ── the check itself ────────────────────────────────────────────────────────

def test_01_a_complete_tree_is_usable(repo):
    _pkg(repo, "axios", main="dist/browser/axios.cjs")
    _pkg(repo, "react-native")
    assert app_builder._unusable_node_modules(repo) == []


def test_02_the_reported_failure_is_detected(repo):
    """axios/package.json present, the file its `main` names absent."""
    _pkg(repo, "axios", main="dist/browser/axios.cjs", with_file=False)
    _pkg(repo, "react-native")
    assert app_builder._unusable_node_modules(repo) == ["axios"]


def test_03_a_missing_package_directory_is_detected(repo):
    _pkg(repo, "axios")
    json.dump({"name": "app", "dependencies": {"axios": "^1.0.0",
                                               "apisauce": "^3.0.0"}},
              open(os.path.join(repo, "package.json"), "w"))
    assert app_builder._unusable_node_modules(repo) == ["apisauce"]


def test_04_a_package_with_no_main_is_not_a_failure(repo):
    """Types-only packages, and index.js-by-convention, are legitimate."""
    d = os.path.join(repo, "node_modules", "some-types")
    _write(os.path.join(d, "package.json"), {"name": "some-types", "version": "1.0.0"})
    json.dump({"name": "app", "dependencies": {"some-types": "^1.0.0"}},
              open(os.path.join(repo, "package.json"), "w"))
    assert app_builder._unusable_node_modules(repo) == []


def test_05_a_main_pointing_at_a_directory_resolves(repo):
    """`main: "lib"` with lib/index.js is standard and must not be flagged."""
    d = os.path.join(repo, "node_modules", "libby")
    _write(os.path.join(d, "package.json"), {"name": "libby", "version": "1",
                                             "main": "lib"})
    os.makedirs(os.path.join(d, "lib"))
    open(os.path.join(d, "lib", "index.js"), "w").write("x")
    json.dump({"name": "app", "dependencies": {"libby": "^1.0.0"}},
              open(os.path.join(repo, "package.json"), "w"))
    assert app_builder._unusable_node_modules(repo) == []


def test_06_a_scoped_package_is_checked_under_its_scope(repo):
    _pkg(repo, "@react-native/metro-config", with_file=False)
    assert app_builder._unusable_node_modules(repo) == ["@react-native/metro-config"]


# ── ensure_node_modules: repair, then re-verify ─────────────────────────────

def test_07_a_sound_tree_installs_nothing(repo, monkeypatch):
    _pkg(repo, "axios")
    calls = []
    monkeypatch.setattr("automation.projects.builder._run",
                        lambda *a, **k: calls.append(a) or (True, ""))
    ok, msg = app_builder.ensure_node_modules(repo)
    assert ok and not calls, f"installed unnecessarily: {calls}"


def test_08_a_broken_tree_triggers_an_install(repo, monkeypatch):
    _pkg(repo, "axios", main="dist/browser/axios.cjs", with_file=False)
    ran = []

    def _fake(cmd, cwd=None, timeout=None):
        ran.append(cmd)
        # The install "succeeds" and repairs the tree.
        target = os.path.join(repo, "node_modules", "axios", "dist", "browser")
        os.makedirs(target, exist_ok=True)
        open(os.path.join(target, "axios.cjs"), "w").write("x")
        return True, ""

    monkeypatch.setattr("automation.projects.builder._run", _fake)
    ok, msg = app_builder.ensure_node_modules(repo)
    assert ok, msg
    assert ran and ran[0][-1] == "install", ran


def test_09_an_install_that_lies_is_caught(repo, monkeypatch):
    """CASE the isdir check missed: exit 0, tree still unusable."""
    _pkg(repo, "axios", main="dist/browser/axios.cjs", with_file=False)
    monkeypatch.setattr("automation.projects.builder._run",
                        lambda *a, **k: (True, "added 1200 packages"))
    ok, msg = app_builder.ensure_node_modules(repo)
    assert not ok, "a successful exit code was trusted over the tree"
    assert "axios" in msg
    assert "still cannot resolve" in msg


def test_10_eresolve_retries_with_legacy_peer_deps(repo, monkeypatch):
    _pkg(repo, "axios", with_file=False)
    ran = []

    def _fake(cmd, cwd=None, timeout=None):
        ran.append(cmd)
        if "--legacy-peer-deps" not in cmd:
            return False, "npm ERESOLVE unable to resolve dependency tree"
        open(os.path.join(repo, "node_modules", "axios", "index.js"), "w").write("x")
        return True, ""

    monkeypatch.setattr("automation.projects.builder._run", _fake)
    ok, msg = app_builder.ensure_node_modules(repo)
    assert ok, msg
    assert len(ran) == 2 and "--legacy-peer-deps" in ran[1]


def test_11_a_non_js_project_is_a_no_op(tmp_path, monkeypatch):
    calls = []
    monkeypatch.setattr("automation.projects.builder._run",
                        lambda *a, **k: calls.append(a) or (True, ""))
    ok, msg = app_builder.ensure_node_modules(str(tmp_path))
    assert ok and not calls


def test_12_the_error_names_the_command_to_run(repo, monkeypatch):
    """The message must be actionable on the machine that failed."""
    _pkg(repo, "axios", with_file=False)
    monkeypatch.setattr("automation.projects.builder._run",
                        lambda *a, **k: (True, ""))
    ok, msg = app_builder.ensure_node_modules(repo)
    assert not ok
    assert "install" in msg and repo in msg


# ── wired into the path that actually failed ────────────────────────────────

def test_13_the_bundler_verifies_dependencies_first(repo, monkeypatch):
    """_ensure_ios_jsbundle must not shell out to Metro over a broken tree."""
    import inspect
    src = inspect.getsource(app_builder._ensure_ios_jsbundle)
    assert "ensure_node_modules" in src, \
        "the bundler can still run Metro against an unusable node_modules"
    # And it must be checked BEFORE the bundle command is built.
    assert src.index("ensure_node_modules") < src.index("react-native")
