# ── a newer Yarn poisons .yarnrc.yml for the older one ──────────────────────
#
# Found on the reporting machine after the lockfile was already fixed: a Yarn 4
# run had rewritten .yarnrc.yml from one line into six keys, and Yarn 3.6.4 then
# refused to start at all — "Unrecognized or legacy configuration settings
# found: approvedGitRepositories". Pinning the Yarn major cannot help: this
# fails BEFORE resolution. And .yarnrc.yml is typically untracked, so
# `git checkout` cannot undo it.

YARN4_RC = """compressionLevel: mixed
enableGlobalCache: false
approvedGitRepositories:
  - https://github.com/example/thing
nodeLinker: node-modules
"""


def test_25_a_yarn4_rewritten_yarnrc_is_detected(repo):
    open(os.path.join(repo, "yarn.lock"), "w").write(BERRY_LOCK)   # cacheKey 8 -> yarn@3
    open(os.path.join(repo, ".yarnrc.yml"), "w").write(YARN4_RC)
    bad = app_builder._yarnrc_poisoned(repo, "3")
    assert "approvedGitRepositories" in bad
    assert "enableGlobalCache" in bad and "compressionLevel" in bad


def test_26_a_clean_yarnrc_is_not_flagged(repo):
    open(os.path.join(repo, ".yarnrc.yml"), "w").write("nodeLinker: node-modules\n")
    assert app_builder._yarnrc_poisoned(repo, "3") == []


def test_27_yarn4_projects_are_allowed_their_own_settings(repo):
    """Only an OLDER Yarn rejects newer keys; a yarn@4 project is fine."""
    open(os.path.join(repo, ".yarnrc.yml"), "w").write(YARN4_RC)
    assert app_builder._yarnrc_poisoned(repo, "4") == []


def test_28_a_missing_yarnrc_is_not_an_error(repo):
    assert app_builder._yarnrc_poisoned(repo, "3") == []


def test_29_the_install_stops_before_yarn_refuses_to_start(repo, monkeypatch):
    """The guard must fire instead of letting Yarn fail with its own opaque error."""
    _pkg(repo, "axios", with_file=False)
    open(os.path.join(repo, "yarn.lock"), "w").write(BERRY_LOCK)
    open(os.path.join(repo, ".yarnrc.yml"), "w").write(YARN4_RC)
    ran = []
    monkeypatch.setattr("automation.projects.builder._run",
                        lambda *a, **k: ran.append(a) or (True, ""))
    ok, msg = app_builder.ensure_node_modules(repo)
    assert not ok, "the install ran against a .yarnrc.yml Yarn 3 cannot read"
    assert not ran, f"should not have shelled out at all: {ran}"
    assert "approvedGitRepositories" in msg
    assert "nodeLinker: node-modules" in msg, "must say how to recover"
