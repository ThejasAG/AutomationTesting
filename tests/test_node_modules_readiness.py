# ── the wrong Yarn major silently rewrites a Berry lockfile ─────────────────
#
# The real cause of the reported build failure, found only after the node_modules
# checks above came back clean: the tree was COMPLETE, it just held the wrong
# versions. Yarn 1 cannot read a Berry lockfile (`__metadata:`), does not error,
# and re-resolves every caret range to the newest release — turning a project
# pinned to axios 1.7.7 into axios 1.20.0. Axios >=1.11 points `main` at
# dist/browser/axios.cjs, and RN 0.68's Metro has sourceExts
# ["js","json","ts","tsx"] with no "cjs", so the bundle then fails.

BERRY_LOCK = """# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 6
  cacheKey: 8

"axios@npm:^1.7.7":
  version: 1.7.7
"""

CLASSIC_LOCK = """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

axios@^1.7.7:
  version "1.20.0"
"""


def test_18_a_berry_lockfile_pins_the_yarn_major(repo):
    """corepack alone is not enough: with no `packageManager` field it falls
    back to whatever yarn is installed globally, which on the reporting machine
    was Yarn 1. The major is therefore pinned from the lockfile's own cacheKey.
    """
    open(os.path.join(repo, "yarn.lock"), "w").write(BERRY_LOCK)
    pm = app_builder.detect_package_manager(repo)
    assert pm[0] == "corepack"
    assert pm[1].startswith("yarn@"), pm
    assert pm[1] != "yarn@1", "Yarn 1 cannot read a Berry lockfile"
    assert pm[1] == "yarn@3", f"cacheKey 8 is Yarn 3, got {pm[1]}"


def test_19_cachekey_selects_the_matching_major(repo):
    """Even Yarn 4 against a Yarn 3 lockfile rewrites the fsevents patch
    protocol and fails --immutable, so the major must match, not merely be Berry.
    """
    for cachekey, want in (("8", "yarn@3"), ("9", "yarn@4"), ("10", "yarn@4")):
        open(os.path.join(repo, "yarn.lock"), "w").write(
            BERRY_LOCK.replace("cacheKey: 8", f"cacheKey: {cachekey}"))
        assert app_builder.detect_package_manager(repo)[1] == want, cachekey


def test_20_an_unknown_cachekey_still_avoids_yarn_1(repo):
    open(os.path.join(repo, "yarn.lock"), "w").write(
        BERRY_LOCK.replace("cacheKey: 8", "cacheKey: 99"))
    pm = app_builder.detect_package_manager(repo)
    assert pm[1] == "yarn@stable", pm


def test_21_a_classic_lockfile_still_uses_plain_yarn(repo):
    """A genuine Yarn 1 project must not be forced onto Berry."""
    open(os.path.join(repo, "yarn.lock"), "w").write(CLASSIC_LOCK)
    assert app_builder.detect_package_manager(repo) == ["yarn"]


def test_22_no_lockfile_means_npm(repo):
    assert app_builder.detect_package_manager(repo) == ["npm"]


def test_23_a_clobbered_berry_lockfile_is_reported_not_ignored(repo, monkeypatch):
    """The exact silent failure: the install 'succeeds', the tree looks fine,
    and the only evidence is the lockfile's format having changed."""
    _pkg(repo, "axios", with_file=False)
    open(os.path.join(repo, "yarn.lock"), "w").write(BERRY_LOCK)

    def _clobber(cmd, cwd=None, timeout=None):
        # What Yarn 1 does: rewrite the lockfile and "succeed".
        open(os.path.join(repo, "yarn.lock"), "w").write(CLASSIC_LOCK)
        d = os.path.join(repo, "node_modules", "axios")
        open(os.path.join(d, "index.js"), "w").write("x")   # tree looks healthy
        return True, "success Already up-to-date."

    monkeypatch.setattr("automation.projects.builder._run", _clobber)
    ok, msg = app_builder.ensure_node_modules(repo)
    assert not ok, "a destroyed lockfile was reported as a successful install"
    assert "lockfile" in msg.lower()
    assert "git checkout -- yarn.lock" in msg, "the message must say how to recover"


